const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {SOURCES,makeManifest,updateProduct,run} = require('./sync-half-life');
const site = path.resolve(__dirname,'../..');
const source = process.env.SCOOBY_SOURCE_ROOT || path.resolve(site,'../Scooby-Op');
const s = Object.fromEntries(Object.entries(SOURCES).map(([key,file])=>[key,fs.readFileSync(path.join(source,file),'utf8')]));
const entries = m => m.tabs.flatMap(t=>t.categories.flatMap(c=>c.groups.flatMap(g=>g.items)));
const base = makeManifest(s), items=entries(base);
assert.equal(new Set(items.map(i=>i.id)).size,items.length);
assert(!items.some(i=>['esp.health','demo.animate','hl.telemetry'].includes(i.id)));
const visibleCombat = s.combat.slice(s.combat.indexOf('void combatInstallPages'));
const aimModes = visibleCombat.match(/ui\.combo\('Mode',host\.setting\(prefix\.\.'combat.aim'[^\n]+?\{([^}]+)\}/)[1];
const modeLabels = [...aimModes.matchAll(/'([^']+)'/g)].map(m=>m[1]);
assert(items.find(i=>i.id==='hl.combat.aim').settings.includes('Mode: '+modeLabels.join(', ')));
if (!modeLabels.includes('pSilent')) assert(!JSON.stringify(items).includes('pSilent'));
const fovSource=s.view.match(/\{"fov","FOV",([\d.]+)f,([\d.]+)f,([\d.]+)f/);
assert(items.find(i=>i.id==='hl.view.fov').settings.includes(`Range: ${Number(fovSource[2])}–${Number(fovSource[3])}; default: ${Number(fovSource[1])}`));
assert(items.find(i=>i.id==='hl.campaign.spawn').settings.includes('Quantity: 1–8'));
const changed = {...s,combat:s.combat.replace('{"combat.aim","Aimbot"}', '{"combat.aim","Aimbot"},{"combat.fixture","Test control"}')};
const extended = makeManifest(changed);
assert.equal(entries(extended).length,items.length+1);
assert(entries(extended).some(i=>i.id==='hl.combat.fixture'&&i.label==='Test control'));
const html = fs.readFileSync(path.join(site,'products/half-life-1/index.html'),'utf8');
const {applyMetadata}=require('../seo-metadata');
const product = updateProduct(html,extended,applyMetadata);
assert(product.includes(`${items.length+1} FEATURES &amp; SETTINGS`));
assert(product.includes('Test control')); // Metadata updates too; tags stay out of the visible page.
assert.equal((product.match(/data-hl-preview /g)||[]).length,(html.match(/data-hl-preview /g)||[]).length);
assert(product.includes('class="product-status is-free">Free'));
assert(!product.includes('Windows build verified'));
assert(!product.includes('<h3>Tags</h3>'));
const removed={...s,combat:s.combat.replace(',{"movement.bunny_hop","Bunny Hop"}','').replace("ui.feature(prefix..'movement.bunny_hop');",'')};
assert.equal(entries(makeManifest(removed)).length,items.length-1);
const withoutBunnyHop = updateProduct(html,makeManifest(removed),applyMetadata);
// Screenshot alt text describes the captured UI and is outside the generated regions.
assert(!withoutBunnyHop.replace(/<img\b[^>]*>/g,'').includes('Bunny Hop'));
assert.deepEqual(withoutBunnyHop.match(/<img\b[^>]*>/g),html.match(/<img\b[^>]*>/g));
assert.throws(()=>makeManifest({...s,combat:s.combat.replace('{"combat.aim","Aimbot"}','{"combat.new_id","Aimbot"}')}),/Unmapped public control|UI mode missing from registry/);
assert.throws(()=>makeManifest({...s,host:s.host.replace('campaignRegisterFeatures(*app);','newModuleRegisterFeatures(*app);')}),/New registry/);
assert.throws(()=>makeManifest({...s,campaign:s.campaign.replace('void campaignRegisterFeatures','void renamedRegisterFeatures')}),/Source structure changed/);
assert.deepEqual(run({sourceRoot:source}).changed,[],'Source and site should already be synced');
console.log(`PASS: ${items.length} controls; new feature, removal, mode/range extraction, schema guards, product preservation and idempotence.`);
