local function choose(t)
    if #t==0 then
        return nil
    end
    return t[math.random(1,#t)]
end

local function family_compatibility(a,b)
    if a==b then
        return 1.0
    end
    local gender_map=FAMILY_COMPATIBILITY[selected_gender] or {}
    local direct=gender_map[a] and gender_map[a][b]
    local reverse=gender_map[b] and gender_map[b][a]
    return direct or reverse or 0
end

local function ranked_donors(seed)
    local cache=donor_rank_cache[selected_gender]
    if cache[seed] then
        return cache[seed]
    end

    local scored={}
    for _,o in ipairs(active_outfits()) do
        if o~=seed then
            local compatibility=family_compatibility(seed.family,o.family)
            if compatibility>0 then
                local distance=outfit_distance(seed,o)
                scored[#scored+1]={o=o, compatibility=compatibility, distance=distance}
            end
        end
    end
    table.sort(scored,function(a,b)
        local aq=a.compatibility/(1+a.distance*.12)
        local bq=b.compatibility/(1+b.distance*.12)
        if aq==bq then
            return a.distance<b.distance
        end
        return aq>bq
    end)
    cache[seed]=scored
    return scored
end

local function weighted_donor(seed,profile,excluded)
    local ranked=ranked_donors(seed)
    local limit=math.min(profile.donor_limit,#ranked)
    local total=0
    local weighted={}
    for rank=1,limit do
        local entry=ranked[rank]
        if not excluded or not excluded[entry.o] then
            local same_family=entry.o.family==seed.family and 1.8 or 1.0
            local weight=same_family*(entry.compatibility^profile.compatibility_power)
                / ((1+entry.distance*profile.distance_scale)*(rank^profile.rank_power))
            if weight>0 then
                total=total+weight
                weighted[#weighted+1]={o=entry.o, ceiling=total}
            end
        end
    end
    if total<=0 then
        return nil
    end
    local roll=math.random()*total
    for _,entry in ipairs(weighted) do
        if roll<=entry.ceiling then
            return entry.o
        end
    end
    return weighted[#weighted].o
end

local function copy_bundle(dst,src,indices)
    for _,i in ipairs(indices) do
        dst.c[i]=clone_triplet(src.c and src.c[i])
    end
end
local function copy_props(dst,src)
    for i=1,9 do
        dst.p[i]=clone_pair(src.p and src.p[i])
    end
end

local function copy_prop_group(dst,src,indices)
    for _,i in ipairs(indices) do
        dst.p[i]=clone_pair(src.p and src.p[i])
    end
end

local function values_differ(a,b,count)
    if type(a)~="table" or type(b)~="table" then
        return true
    end
    for i=1,count do
        if a[i]~=b[i] then
            return true
        end
    end
    return false
end

local function bundle_differs(a,b,indices)
    for _,i in ipairs(indices) do
        if values_differ(a.c and a.c[i],b.c and b.c[i],3) then
            return true
        end
    end
    return false
end

local function prop_group_differs(a,b,indices)
    for _,i in ipairs(indices) do
        if values_differ(a.p and a.p[i],b.p and b.p[i],2) then
            return true
        end
    end
    return false
end

local function weighted_name_choice(entries)
    local total=0
    for _,entry in ipairs(entries) do
        total=total+entry.weight
    end
    if total<=0 then
        return nil
    end
    local roll=math.random()*total
    local running=0
    for _,entry in ipairs(entries) do
        running=running+entry.weight
        if roll<=running then
            return entry.name
        end
    end
    return entries[#entries].name
end

local function pick_bundle_names(result,donor,count)
    local choices={}
    local weights={top=3.2,bottom=3.0,mask=2.0,hair=1.7}
    local locked={top=lock_top,bottom=lock_bottom,mask=lock_mask,hair=lock_hair}
    for name,indices in pairs(BUNDLES) do
        if not locked[name] and bundle_differs(result,donor,indices) then
            choices[#choices+1]={name=name,weight=weights[name] or 1}
        end
    end

    local selected={}
    count=math.min(count,#choices)
    for _=1,count do
        local name=weighted_name_choice(choices)
        if not name then
            break
        end
        selected[#selected+1]=name
        for i=#choices,1,-1 do
            if choices[i].name==name then
                table.remove(choices,i)
                break
            end
        end
    end
    return selected
end

local function mutate_props(result,seed,primary,profile)
    if lock_props or math.random()>profile.prop_chance then
        return
    end

    local donor=primary
    if mutation_level>=2 and math.random()<(mutation_level==3 and .35 or .20) then
        local excluded={}
        excluded[primary]=true
        local accent=weighted_donor(seed,profile,excluded)
        if accent and family_compatibility(primary.family,accent.family)>0 then
            donor=accent
        end
    end

    local available={}
    for _,name in ipairs(PROP_GROUP_ORDER) do
        if prop_group_differs(result,donor,PROP_GROUPS[name]) then
            available[#available+1]=name
        end
    end
    if #available==0 then
        return
    end

    local max_groups=math.min(profile.max_prop_groups,#available)
    local group_count=mutation_level==1 and 1 or math.random(1,max_groups)
    for i=#available,2,-1 do
        local j=math.random(1,i)
        available[i],available[j]=available[j],available[i]
    end
    for i=1,group_count do
        copy_prop_group(result,donor,PROP_GROUPS[available[i]])
    end
end

local function outfit_fingerprint(o)
    local parts={tostring(o.model)}
    for i=1,12 do
        local v=o.c[i]
        parts[#parts+1]=tostring(v[1])..":"..tostring(v[2])..":"..tostring(v[3])
    end
    for i=1,9 do
        local v=o.p[i]
        parts[#parts+1]=tostring(v[1])..":"..tostring(v[2])
    end
    return table.concat(parts,"|")
end

local function outfit_value_differences(a,b,stop_after)
    local differences=0
    for i=1,12 do
        for j=1,3 do
            if a.c[i][j]~=b.c[i][j] then
                differences=differences+1
                if differences>stop_after then
                    return differences
                end
            end
        end
    end
    for i=1,9 do
        for j=1,2 do
            if a.p[i][j]~=b.p[i][j] then
                differences=differences+1
                if differences>stop_after then
                    return differences
                end
            end
        end
    end
    return differences
end

local function is_recent_generation(o)
    local fingerprint=outfit_fingerprint(o)
    for _,entry in ipairs(recent_generations) do
        if entry.model==o.model and (entry.fingerprint==fingerprint or outfit_value_differences(o,entry.outfit,2)<=2) then
            return true
        end
    end
    return false
end

local function remember_generation(o)
    recent_generations[#recent_generations+1]={model=o.model,fingerprint=outfit_fingerprint(o),outfit=clone_outfit(o)}
    if #recent_generations>recent_generation_limit then
        table.remove(recent_generations,1)
    end
end

local function build_mutation(seed,current,profile)
    local result=clone_outfit(seed)
    result.model=selected_model()

    -- Locked sections always come from the player's pre-generation appearance.
    if lock_top then
        copy_bundle(result,current,BUNDLES.top)
    end
    if lock_bottom then
        copy_bundle(result,current,BUNDLES.bottom)
    end
    if lock_mask then
        copy_bundle(result,current,BUNDLES.mask)
    end
    if lock_hair then
        copy_bundle(result,current,BUNDLES.hair)
    end
    if lock_props then
        copy_props(result,current)
    end

    local primary=weighted_donor(seed,profile)
    if primary then
        local bundle_count=math.random(profile.min_bundles,profile.max_bundles)
        local bundle_names=pick_bundle_names(result,primary,bundle_count)
        for _,name in ipairs(bundle_names) do
            copy_bundle(result,primary,BUNDLES[name])
        end
        mutate_props(result,seed,primary,profile)
    end

    return normalize_outfit(result,seed)
end

local function generate_outfit(similar_to_current)
    if not is_supported_model() then
        toast(selected_gender == "female" and "Female mode selected, but the current ped model does not match mp_f_freemode_01." or "Male mode selected, but the current ped model does not match mp_m_freemode_01.")
        return
    end
    local pool=candidates_for_family(selected_family())
    if #pool==0 then toast("No source outfits in this style.") return end

    local seed
    if similar_to_current then
        local current=capture_current()
        local best,best_d=nil,1e9
        for _,o in ipairs(pool) do
            local d=outfit_distance(current,o)
            if d<best_d then best,best_d=o,d end
        end
        seed=best
    else
        seed=choose(pool)
    end
    if not seed then return end

    local current=capture_current()
    local profile=MUTATION_PROFILES[mutation_level] or MUTATION_PROFILES[2]
    local result=nil
    local max_attempts=10
    for _=1,max_attempts do
        local candidate=build_mutation(seed,current,profile)
        if candidate and validate_outfit(candidate) then
            result=candidate
            if not is_recent_generation(candidate) then
                break
            end
        end
    end

    if not result or not validate_outfit(result) then
        toast("Could not build a valid outfit from the selected references.")
        return
    end

    generation_counter=generation_counter+1
    result.name=string.format("Generated %03d",generation_counter)
    result.label=seed.name
    result.family=seed.family
    push_history()
    if apply_outfit(result) then
        remember_generation(result)
        toast(string.upper(selected_gender).." | Generated from "..seed.name.." | "..string.upper(seed.family))
    end
end

local function previous_outfit()
    if #history==0 then toast("No previous outfit yet.") return end
    local o=history[#history]
    if ENTITY.GET_ENTITY_MODEL(ped_id()) ~= (o.model or selected_model()) then
        toast("Your current character does not match the previous outfit.")
        return
    end
    table.remove(history,#history)
    apply_outfit(o)
    toast("Restored previous outfit.")
end

