local function json_escape(s)
    s=tostring(s)
    s=s:gsub("\\","\\\\")
    s=s:gsub('"','\\"')
    return s
end

local function export_last()
    if not last_generated then
        toast("Generate an outfit first.")
        return
    end

    local o = last_generated
    local filename = "OutfitForge_"..os.date("%Y%m%d_%H%M%S")..".json"
    -- Use Cherax's own menu root. This stays inside Cherax's allowed filesystem.
    -- GetMenuRootPath() is the Cherax folder; Outfits sits directly inside it.
    local export_dir = FileMgr.GetMenuRootPath() .. "\\Outfits"
    local path = export_dir .. "\\" .. filename
    local f = io.open(path, "w")

    if not f then
        toast("Export failed - Cherax could not write the file.")
        return
    end

    f:write('{\n')
    f:write('  "format": "Cherax Entity",\n')
    f:write('  "type": 2,\n')
    f:write('  "model": '..tostring(o.model or selected_model())..',\n')
    f:write('  "baseFlags": '..tostring(o.baseFlags or 66879)..',\n')
    f:write('  "components": {\n')
    for i=1,12 do
        local v=o.c[i]
        f:write(string.format(
            '    "%s": {"drawable": %d, "texture": %d, "palette": %d}%s\n',
            json_escape(COMPONENT_NAMES[i]), v[1], v[2], v[3], i<12 and ',' or ''
        ))
    end
    f:write('  },\n')
    f:write('  "props": {\n')
    for i=1,9 do
        local v=o.p[i]
        f:write(string.format(
            '    "%s": {"drawable": %d, "texture": %d}%s\n',
            json_escape(PROP_NAMES[i]), v[1], v[2], i<9 and ',' or ''
        ))
    end
    f:write('  },\n')
    -- Cherax's outfit loader expects the normal face_features structure.
    -- An empty object can cause "Load Outfit" to throw an exception.
    f:write('  "face_features": {\n')
    f:write('    "Nose Width": 0.0,\n')
    f:write('    "Nose Peak": 0.0,\n')
    f:write('    "Nose Length": 0.0,\n')
    f:write('    "Nose Bone Curveness": 0.0,\n')
    f:write('    "Nose Tip": 0.0,\n')
    f:write('    "Nose Bone Twist": 0.0,\n')
    f:write('    "Eyebrow Height": 0.0,\n')
    f:write('    "Eyebrow Indent": 0.0,\n')
    f:write('    "Cheek Bones": 0.0,\n')
    f:write('    "Cheek Sideways Bone Size": 0.0,\n')
    f:write('    "Cheek Bones Width": 0.0,\n')
    f:write('    "Eye Opening": 0.0,\n')
    f:write('    "Lip Thickness": 0.0,\n')
    f:write('    "Jaw Bone Width": 0.0,\n')
