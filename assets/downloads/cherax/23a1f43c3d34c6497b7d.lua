local function valid_number(v)
    return type(v)=="number" and v==v
end

local function clone_pair(v)
    if type(v)~="table" then
        return {-1,-1}
    end
    return {valid_number(v[1]) and v[1] or -1, valid_number(v[2]) and v[2] or -1}
end

local function clone_triplet(v)
    if type(v)~="table" then
        return {0,0,0}
    end
    return {
        valid_number(v[1]) and v[1] or 0,
        valid_number(v[2]) and v[2] or 0,
        valid_number(v[3]) and v[3] or 0
    }
end

local function clone_outfit(o)
    local c, p = {}, {}
    local source_c=type(o.c)=="table" and o.c or {}
    local source_p=type(o.p)=="table" and o.p or {}
    for i=1,12 do
        c[i]=clone_triplet(source_c[i])
    end
    for i=1,9 do
        p[i]=clone_pair(source_p[i])
    end
    return {name=o.name, family=o.family, label=o.label, baseFlags=o.baseFlags, model=o.model or selected_model(), c=c, p=p}
end

local function normalize_outfit(o,fallback)
    if type(o)~="table" then
        return nil
    end
    local fallback_c=type(fallback)=="table" and type(fallback.c)=="table" and fallback.c or {}
    local fallback_p=type(fallback)=="table" and type(fallback.p)=="table" and fallback.p or {}
    o.c=type(o.c)=="table" and o.c or {}
    o.p=type(o.p)=="table" and o.p or {}

    for i=1,12 do
        local v=type(o.c[i])=="table" and o.c[i] or {}
        local f=type(fallback_c[i])=="table" and fallback_c[i] or {0,0,0}
        o.c[i]={
            valid_number(v[1]) and v[1] or (valid_number(f[1]) and f[1] or 0),
            valid_number(v[2]) and v[2] or (valid_number(f[2]) and f[2] or 0),
            valid_number(v[3]) and v[3] or (valid_number(f[3]) and f[3] or 0)
        }
    end
    for i=1,9 do
        local v=type(o.p[i])=="table" and o.p[i] or {}
        local f=type(fallback_p[i])=="table" and fallback_p[i] or {-1,-1}
        o.p[i]={
            valid_number(v[1]) and v[1] or (valid_number(f[1]) and f[1] or -1),
            valid_number(v[2]) and v[2] or (valid_number(f[2]) and f[2] or -1)
        }
    end
    o.model=selected_model()
    return o
end

local function validate_outfit(o)
    if type(o)~="table" or type(o.c)~="table" or type(o.p)~="table" or not valid_number(o.model) then
        return false
    end
    for i=1,12 do
        local v=o.c[i]
        if type(v)~="table" or not valid_number(v[1]) or not valid_number(v[2]) or not valid_number(v[3]) then
            return false
        end
    end
    for i=1,9 do
        local v=o.p[i]
        if type(v)~="table" or not valid_number(v[1]) or not valid_number(v[2]) then
            return false
        end
    end
    return true
end

local function capture_current()
    local ped = ped_id()
    local o = {name="Current", family="current", label="Current", baseFlags=0, model=ENTITY.GET_ENTITY_MODEL(ped), c={}, p={}}
    for component=0,11 do
        o.c[component+1] = {
            PED.GET_PED_DRAWABLE_VARIATION(ped, component),
            PED.GET_PED_TEXTURE_VARIATION(ped, component),
            PED.GET_PED_PALETTE_VARIATION(ped, component)
        }
    end
    for prop=0,8 do
        o.p[prop+1] = {
            PED.GET_PED_PROP_INDEX(ped, prop),
            PED.GET_PED_PROP_TEXTURE_INDEX(ped, prop)
        }
    end
    return o
end

local function push_history()
    history[#history+1] = capture_current()
    if #history > history_limit then table.remove(history,1) end
end

local function apply_outfit(o)
    if not validate_outfit(o) then
        toast("Outfit data was incomplete and could not be applied.")
        return false
    end
    local required=o.model or selected_model()
    local actual=current_model()

    if strict_model_check and actual ~= required then
        toast(required == FEMALE_MODEL and "Switch to the female freemode character first." or "Switch to the male freemode character first.")
        return false
    end

    local ped=ped_id()
    for component=0,11 do
        local v=o.c[component+1]
        PED.SET_PED_COMPONENT_VARIATION(ped, component, v[1], v[2], v[3])
    end
    for prop=0,8 do
        local v=o.p[prop+1]
        if not v[1] or v[1] < 0 then
            PED.CLEAR_PED_PROP(ped, prop)
        else
            PED.SET_PED_PROP_INDEX(ped, prop, v[1], v[2], true)
        end
    end
    last_generated=clone_outfit(o)
    return true
end

local function outfit_distance(a,b)
    local weights={0.2,1.0,0.35,2.0,1.7,1.6,1.3,0.8,1.5,1.5,0.8,2.0}
    local score=0
    for i=1,12 do
        local av=type(a.c)=="table" and type(a.c[i])=="table" and a.c[i] or {}
        local bv=type(b.c)=="table" and type(b.c[i])=="table" and b.c[i] or {}
        if av[1] ~= bv[1] then
            score=score+weights[i]
        end
        if av[2] ~= bv[2] then
            score=score+weights[i]*0.35
        end
    end
    for i=1,9 do
        local av=type(a.p)=="table" and type(a.p[i])=="table" and a.p[i] or {}
        local bv=type(b.p)=="table" and type(b.p[i])=="table" and b.p[i] or {}
        if av[1] ~= bv[1] then
            score=score+0.45
        end
        if av[2] ~= bv[2] then
            score=score+0.15
        end
    end
    return score
end

